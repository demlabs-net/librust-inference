//! Встроенные плагины движков.
//!
//! Правило раскладки: всё, что относится к одной архитектуре, живёт в ОДНОМ
//! каталоге `plugins/<arch>/` — конфиг/схема файла, слои forward, загрузчик
//! весов этого формата. Плагин объявляет себя через [`crate::plugin::EnginePlugin`]
//! и попадает в [`crate::plugin::NATIVE_REGISTRY`]; сервис и балансировщик
//! видят его способности, не зная имён модулей.
//!
//! Сейчас встроены (идут в комплекте с крейтом):
//! * `qwen` — dense `v3` и гибрид `v3.5` (GDN, включая Qwen3.8-27B);
//! * `qwen4exp` — Qwen3.8-Flash-Next (MoE 512/top-10 + shared, hyper-connections,
//!   QSA-индексер, PLE): forward в работе, веса читаются из контейнера NINFER.
//!
//! Внешние движки (Infernix/Basalt/Strata/vLLM/…) плагинами не считаются:
//! это адаптеры [`crate::plugin::ExternalEngine`], которые сервис создаёт в
//! рантайме по манифесту.

