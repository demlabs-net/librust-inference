/// IQ2_XS (74 Б/256): d @0, qs[32] u16 @2, scales[8] @66. Для позиции p:
/// ib32 = p/32, l = (p%32)/8, j = p%8; q = qs[4·ib32+l]; idx = q & 511,
/// signs = ksigns[q >> 9]; db = d·(0.5 + sc)·0.25, sc = l<2 ? scales[ib32]&0xF
/// : scales[ib32]>>4; value = db·grid[idx][j]·sign(j).
pub(crate) fn dequant_iq2_xs(data: &[u8]) -> Vec<f32> {
    let mut out = Vec::with_capacity(data.len() / 74 * 256);
    for blk in data.chunks_exact(74) {
        let d = f16_to_f32([blk[0], blk[1]]);
        let qs = &blk[2..66];
        let scales = &blk[66..74];
        for p in 0..256usize {
            let ib32 = p / 32;
            let l = (p % 32) / 8;
            let j = p % 8;
            // qs — БАЙТОВЫЙ срез: qs[4·ib32+l] эталона (uint16) = байты
            // 8·ib32 + 2·l.
            let q = u16::from_le_bytes([qs[8 * ib32 + 2 * l], qs[8 * ib32 + 2 * l + 1]]);
            let idx = (q & 511) as usize;
            let signs = KSIGNS_IQ2XS[(q >> 9) as usize];
            let sc = if l < 2 {
                scales[ib32] & 0xF
            } else {
                scales[ib32] >> 4
            };
            let db = d * (0.5 + sc as f32) * 0.25;
            let g = ((IQ2XS_GRID[idx] >> (8 * j)) & 0xFF) as f32;
            let sgn = if signs & (1u8 << j) != 0 { -1.0 } else { 1.0 };
            out.push(db * g * sgn);
        }
    }
    out
}

/// IQ2_S (82 Б/256): d @0, qs[64] @2, qh[8] @66, scales[8] @74; signs —
/// qs[32..64]. idx = qs[4·ib32+l] | ((qh[ib32] << (8−2l)) & 0x300).
